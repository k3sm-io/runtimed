// Command gen writes shim/shadow_table.h, the path-rebase interposer's
// {host, copy} table, from the shadowset list. Run it through go generate in
// pkg/shadowset; its test fails when the committed header is stale.
//
// Usage:
//
//	go run ./gen <output.h>
package main

import (
	"bytes"
	"fmt"
	"os"
	"strconv"

	"k3sm.io/runtimed/pkg/shadowset"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen <output.h>")
		os.Exit(2)
	}
	if err := os.WriteFile(os.Args[1], render(shadowset.Entries()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// render returns the header for entries: one {host, copy} row per exec path,
// in declaration order, and K3SM_SHADOW_COPY_MAX, the longest copy name, which
// bounds the shadow directory the interposer accepts.
func render(entries []shadowset.Entry) []byte {
	var b bytes.Buffer
	b.WriteString(`/*
Copyright The k3sm Authors.

Licensed under the Apache License, Version 2.0 (the "License");
you may not use this file except in compliance with the License.
You may obtain a copy of the License at

    http://www.apache.org/licenses/LICENSE-2.0

Unless required by applicable law or agreed to in writing, software
distributed under the License is distributed on an "AS IS" BASIS,
WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
See the License for the specific language governing permissions and
limitations under the License.
*/

/*
 * Code generated by k3sm.io/runtimed/pkg/shadowset/gen. DO NOT EDIT.
 *
 * The host exec paths the node keeps a re-signed copy for, and the copy each
 * maps to (a file name under K3SM_SHADOW_DIR). The list is declared in
 * pkg/shadowset; edit it there and run go generate ./pkg/shadowset.
 */

#ifndef K3SM_SHADOW_TABLE_H
#define K3SM_SHADOW_TABLE_H

`)
	longest := 0
	for _, e := range entries {
		longest = max(longest, len(e.Copy))
	}
	fmt.Fprintf(&b, "/* The longest copy name, in bytes. */\n#define K3SM_SHADOW_COPY_MAX %d\n\n", longest)
	b.WriteString("static const struct {\n    const char *host;\n    const char *copy;\n} k3sm_shadow_map[] = {\n")
	for _, e := range entries {
		for _, h := range e.Hosts {
			fmt.Fprintf(&b, "    {%s, %s},\n", strconv.Quote(h), strconv.Quote(e.Copy))
		}
	}
	b.WriteString("};\n\n#endif /* K3SM_SHADOW_TABLE_H */\n")
	return b.Bytes()
}
