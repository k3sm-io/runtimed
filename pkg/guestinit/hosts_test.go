// leasedAddr is the guest's DHCP-leased address the re-render maps.
const leasedAddr = "10.0.2.15"

// TestHostsAliasForSubdomainPods is the gate: Plan, then the
// lease-time RenderHosts, then ReplaceEtcFile into a temp dir, read back.
//
// The pod line follows the kubelet's managedHostsFileContent: FQDN first then
// the short name when the pod has a subdomain, the bare name otherwise, and no
// line for a hostNetwork pod. An override pod gets no alias because the host
// sends it no pod_fqdn. A pod_fqdn whose first label is not the hostname's is
// refused, never dropped.
func TestHostsAliasForSubdomainPods(t *testing.T) {
	// The plan-time file on main, byte for byte: the header and the loopback
	// and ip6 lines must not move.
	const planTime = "# Generated by k3sm guest init. Do not edit: this file is a read-only bind.\n" +
		"127.0.0.1\tlocalhost\n" +
		"::1\tlocalhost ip6-localhost ip6-loopback\n" +
		"fe00::0\tip6-localnet\n" +
		"ff00::0\tip6-mcastprefix\n" +
		"ff02::1\tip6-allnodes\n" +
		"ff02::2\tip6-allrouters\n"

	cases := []struct {
		name     string
		hostname string
		fqdn     string
		podLine  string // empty: no pod line
		wantErr  bool
	}{
		{name: "override with subdomain", hostname: "my.host", podLine: leasedAddr + "\tmy.host\n"},
		{name: "hostname plus subdomain", hostname: "web-0", fqdn: "web-0.web.ns.svc.cluster.local",
			podLine: leasedAddr + "\tweb-0.web.ns.svc.cluster.local\tweb-0\n"},
		{name: "setHostnameAsFQDN", hostname: "web-0.web.ns.svc.cluster.local", fqdn: "web-0.web.ns.svc.cluster.local",
			podLine: leasedAddr + "\tweb-0.web.ns.svc.cluster.local\tweb-0\n"},
		{name: "no subdomain", hostname: "p", podLine: leasedAddr + "\tp\n"},
		{name: "hostNetwork", hostname: "", podLine: ""},
		{name: "mismatched label", hostname: "a", fqdn: "b.web.ns.svc.cluster.local", wantErr: true},
		{name: "fqdn with no hostname", hostname: "", fqdn: "web-0.web.ns.svc.cluster.local", wantErr: true},
		{name: "fqdn not a DNS subdomain", hostname: "web-0", fqdn: "web-0.Web.ns", wantErr: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			spec := goldenSpec()
			spec.Hostname, spec.PodFqdn = tc.hostname, tc.fqdn
			plan, err := Plan(spec, Options{})
			if tc.wantErr {
				if !errors.Is(err, ErrInvalidSpec) {
					t.Fatalf("Plan() = %v, want ErrInvalidSpec", err)
				}
				return
			}
			if err != nil {
				t.Fatalf("Plan: %v", err)
			}
			if plan.FQDN != tc.fqdn {
				t.Errorf("plan.FQDN = %q, want %q", plan.FQDN, tc.fqdn)
			}

			// Plan time: no lease, so no pod line, and the rest unchanged.
			if plan.Etc.Hosts != planTime {
				t.Errorf("plan-time hosts:\n%q\nwant:\n%q", plan.Etc.Hosts, planTime)
			}

			// Lay down the plan-time file, then re-render with the lease.
			dir := t.TempDir()
			hostsPath := filepath.Join(dir, "hosts")
			if err := os.WriteFile(hostsPath, []byte(plan.Etc.Hosts), 0o644); err != nil {
				t.Fatal(err)
			}
			before := inode(t, hostsPath)
			rendered := RenderHosts(plan.Hostname, plan.FQDN, leasedAddr)
			if err := ReplaceEtcFile(dir, "hosts", rendered); err != nil {
				t.Fatalf("ReplaceEtcFile: %v", err)
			}

			got, err := os.ReadFile(hostsPath)
			if err != nil {
				t.Fatal(err)
			}
			if want := planTime + tc.podLine; string(got) != want {
				t.Errorf("leased hosts:\n%q\nwant:\n%q", got, want)
			}
			if after := inode(t, hostsPath); after == before {
				t.Error("hosts kept its inode: it was rewritten in place, not replaced by rename")
			}
			entries, err := os.ReadDir(dir)
			if err != nil {
				t.Fatal(err)
			}
			if len(entries) != 1 || entries[0].Name() != "hosts" {
				var names []string
				for _, e := range entries {
					names = append(names, e.Name())
				}
				t.Errorf("dir holds %v after the replace, want only hosts (no temp file left)", names)
			}
			if fi, err := os.Stat(hostsPath); err != nil || fi.Mode().Perm() != 0o644 {
				t.Errorf("hosts mode = %v (err %v), want 0644", fi.Mode().Perm(), err)
			}
			if strings.Count(string(got), "\n"+leasedAddr) > 1 {
				t.Errorf("more than one pod line:\n%s", got)
			}
		})
	}
}

// inode returns the inode number of path.
func inode(t *testing.T, path string) uint64 {
	t.Helper()
	var st unix.Stat_t
	if err := unix.Stat(path, &st); err != nil {
		t.Fatalf("stat %s: %v", path, err)
	}
	return uint64(st.Ino)
}
